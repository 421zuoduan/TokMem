"""Build leak-free NL2Bash training views for InterCode-Bash.

Run as a module from the repository root, for example:

```
python -m compositional_intercode_bash.prepare_data sources
python -m compositional_intercode_bash.prepare_data provenance --exploratory
python -m compositional_intercode_bash.prepare_data procedures --hidden-size 2048
python -m compositional_intercode_bash.prepare_data views --setting sampled --data-seed 1729
```

Both modes remove every retrieved InterCode candidate source group.  A
``--primary`` run additionally requires the exact pinned 200-task source set
and marks the conservative split as paper-ready; ``--exploratory`` uses the
same deletion rule but can never be promoted into a formal run.
"""

